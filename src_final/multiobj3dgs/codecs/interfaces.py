"""Codec lifecycle contracts; importing these does not initialize CUDA."""
from typing import Any, Protocol
from pathlib import Path

class CodecAdapter(Protocol):
    def estimate_host_bytes(self, package_dir: Path) -> int: ...
    def prepare_cpu(self, package_dir: Path, cancel: Any = None) -> Any: ...
    def estimate_device_bytes(self, prepared: Any) -> int: ...
    def realize_gpu(self, prepared: Any) -> Any: ...
    def reconstruct(self, handle: Any, model_time: float, camera: Any) -> Any: ...
    def release(self, handle: Any) -> None: ...
